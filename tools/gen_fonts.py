#!/usr/bin/env python3
"""Render DejaVu fonts into 4-bit anti-aliased bitmap C arrays for the clock.

Usage: python gen_fonts.py <out_header>
Needs Pillow and matplotlib (for the bundled DejaVu TTFs, Bitstream Vera licence).
"""
import os
import sys

import matplotlib
from PIL import Image, ImageDraw, ImageFont

TTF_DIR = os.path.join(os.path.dirname(matplotlib.__file__), "mpl-data", "fonts", "ttf")

# (C name, ttf file, pixel size)
FONTS = [
    ("font_s", "DejaVuSans-Bold.ttf", 14),
    ("font_m", "DejaVuSans-Bold.ttf", 18),
    ("font_l", "DejaVuSans-Bold.ttf", 26),
    ("font_xl", "DejaVuSans-Bold.ttf", 46),
    ("font_xxl", "DejaVuSans-Bold.ttf", 70),  # night clock digits
]
# Fonts that only need a subset (other glyphs keep their advance but no bitmap)
SUBSET = {"font_xl": set("0123456789.,-+ °:"), "font_xxl": set("0123456789: ")}

FIRST, LAST = 32, 126
# Extra glyphs appended after '~': 127 = up triangle, 128 = down triangle, 129 = middle dot, 130 = degree
EXTRA = ["▲", "▼", "·", "°"]


def render(ttf, size, subset=None):
    font = ImageFont.truetype(os.path.join(TTF_DIR, ttf), size)
    ascent, descent = font.getmetrics()
    chars = [chr(c) for c in range(FIRST, LAST + 1)] + EXTRA
    glyphs, bitmap = [], bytearray()
    for ch in chars:
        bbox = font.getbbox(ch)  # (x0, y0, x1, y1) relative to origin at top of ascent
        adv = round(font.getlength(ch))
        if ch in EXTRA[:2]:
            # Triangles in DejaVu are wide; scale them down to text height
            tri = ImageFont.truetype(os.path.join(TTF_DIR, ttf), int(size * 0.7))
            font_use, off_y = tri, int(size * 0.18)
            bbox = tri.getbbox(ch)
            adv = round(tri.getlength(ch))
        else:
            font_use, off_y = font, 0
        x0, y0, x1, y1 = bbox
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        offset = len(bitmap)
        if subset is not None and ch not in subset:
            w = h = 0
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font_use, fill=255)
            px = img.tobytes()
            nib = [p >> 4 for p in px]
            if len(nib) % 2:
                nib.append(0)
            for i in range(0, len(nib), 2):
                bitmap.append((nib[i] << 4) | nib[i + 1])
        glyphs.append((offset, w, h, x0, y0 + off_y, adv))
    return ascent + descent, ascent, glyphs, bitmap


def main(out):
    lines = [
        "// Generated by tools/gen_fonts.py from DejaVu Sans Bold. Do not edit.",
        '#include "gfx.h"',
        "",
    ]
    total = 0
    for name, ttf, size in FONTS:
        height, ascent, glyphs, bitmap = render(ttf, size, SUBSET.get(name))
        total += len(bitmap)
        lines.append(f"static const uint8_t {name}_bits[{len(bitmap)}] = {{")
        for i in range(0, len(bitmap), 24):
            lines.append("  " + ",".join(f"0x{b:02x}" for b in bitmap[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const glyph_t {name}_glyphs[{len(glyphs)}] = {{")
        for g in glyphs:
            lines.append("  {%d,%d,%d,%d,%d,%d}," % g)
        lines.append("};")
        lines.append(
            f"const font_t {name} = {{ {name}_bits, {name}_glyphs, {FIRST}, {len(glyphs)}, {height}, {ascent} }};"
        )
        lines.append("")
    with open(out, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {out}: {total} bytes of glyph bitmaps")


if __name__ == "__main__":
    main(sys.argv[1])
